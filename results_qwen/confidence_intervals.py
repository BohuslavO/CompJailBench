"""95% bootstrap confidence intervals for every cell of MATRIX.md.

Reads the same selection (auroc_sources.csv) and pairing rules as build_matrix.py and
writes CONFIDENCE_INTERVALS.md and CONFIDENCE_INTERVALS.csv.

Resampling unit (the cluster) per attack:
- AgentHarm: base behaviour (the part of the task ID before "-"); its four variants share content.
- DeCompBench: scenario; each scenario appears under three routing strategies.
- SIF and NARCBench: the attack/control pair.
Each bootstrap draw samples clusters with replacement and recomputes AUROC on all pairs in
the drawn clusters (ties count one half). 2000 draws, seed 0, percentile interval.
"""
import csv
import math
import random
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
B = 2000
ATTACKS = {'agentharm': 'AgentHarm', 'semantic_intent_fragmentation': 'Semantic Intent Fragmentation',
           'narcbench_collusion': 'NARCBench', 'decompbench_routing': 'DeCompBench'}
DEFENSES = {'agent_to_agent_monitor': 'Agent-to-Agent Monitor', 'sentinel_agents_message_only': 'Sentinel Agents',
            'cot_observable_reasoning_monitor': 'CoT/rationale monitor', 'narcbench_probing': 'NARCBench Probing'}
UNIT = {'agentharm': 'behaviour', 'decompbench_routing': 'scenario',
        'semantic_intent_fragmentation': 'pair', 'narcbench_collusion': 'pair'}


def auroc(attack, control):
    return sum((a > c) + 0.5 * (a == c) for a in attack for c in control) / (len(attack) * len(control))


def load_pairs(entry):
    pairs = defaultdict(dict)
    with (ROOT / 'raw' / entry['source_csv']).open(encoding='utf-8', newline='') as handle:
        for row in csv.DictReader(handle):
            if row['metric_name'] != entry['metric_name']:
                continue
            arm, task_id = row['condition'], row['task_id']
            if entry['pair_key'] == 'narcbench_task_suffix':
                task_id = task_id.removesuffix('_collusion' if arm == 'attack' else '_control')
            value = float(row['metric_value'])
            assert math.isfinite(value) and arm not in pairs[task_id, row['strategy']]
            pairs[task_id, row['strategy']][arm] = value
    return {key: pair for key, pair in pairs.items() if len(pair) == 2}


def cluster_of(attack, key):
    task_id, strategy = key
    if attack == 'agentharm':
        return task_id.split('-')[0]
    if attack == 'decompbench_routing':
        return task_id
    return key


rows = []
with (ROOT / 'auroc_sources.csv').open(encoding='utf-8', newline='') as handle:
    selection = list(csv.DictReader(handle))
for entry in selection:
    pairs = load_pairs(entry)
    assert len(pairs) == int(entry['expected_pairs']), (entry['source_csv'], len(pairs))
    clusters = defaultdict(list)
    for key, pair in pairs.items():
        clusters[cluster_of(entry['attack_method'], key)].append(pair)
    names = sorted(clusters, key=str)
    point = auroc([p['attack'] for p in pairs.values()], [p['benign_control'] for p in pairs.values()])
    rng = random.Random(0)
    draws = []
    for _ in range(B):
        drawn = [p for _ in names for p in clusters[rng.choice(names)]]
        draws.append(auroc([p['attack'] for p in drawn], [p['benign_control'] for p in drawn]))
    draws.sort()
    low, high = draws[int(0.025 * B)], draws[int(0.975 * B) - 1]
    rows.append(dict(attack=ATTACKS[entry['attack_method']], defense=DEFENSES[entry['defense_method']],
                     auroc=round(point, 4), ci_low=round(low, 3), ci_high=round(high, 3), pairs=len(pairs),
                     clusters=len(names), unit=UNIT[entry['attack_method']],
                     excludes_chance=low > 0.5 or high < 0.5, provenance=entry['provenance']))

with (ROOT / 'CONFIDENCE_INTERVALS.csv').open('w', encoding='utf-8', newline='') as handle:
    writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
    writer.writeheader()
    writer.writerows(rows)

cell = {(r['attack'], r['defense']): r for r in rows}
lines = ['# Confidence intervals for the Qwen 4x4 matrix', '',
         'Generated by `confidence_intervals.py` from the cells selected in `auroc_sources.csv`. '
         'Percentile bootstrap, 2000 draws, seed 0. Each draw resamples clusters with replacement: '
         'AgentHarm by base behaviour, DeCompBench by scenario, SIF and NARCBench by pair. '
         '**Bold** marks intervals that exclude 0.5.', '',
         '| Attack | ' + ' | '.join(DEFENSES.values()) + ' |', '|---|' + '---:|' * 4]
for attack in ATTACKS.values():
    out = []
    for defense in DEFENSES.values():
        r = cell[attack, defense]
        text = f"{r['auroc']:.3f} [{r['ci_low']:.2f}, {r['ci_high']:.2f}]"
        out.append(f'**{text}**' if r['excludes_chance'] else text)
    lines.append(f'| {attack} | ' + ' | '.join(out) + ' |')
lines += ['', '| Attack | Pairs | Clusters | Unit |', '|---|---:|---:|---|']
for attack in ATTACKS.values():
    r = cell[attack, 'Agent-to-Agent Monitor']
    lines.append(f"| {attack} | {r['pairs']} | {r['clusters']} | {r['unit']} |")
note = [r for r in rows if r['pairs'] != cell[r['attack'], 'Agent-to-Agent Monitor']['pairs']]
for r in note:
    lines.append(f"\n{r['attack']} × {r['defense']} uses {r['pairs']} pairs in {r['clusters']} clusters.")
(ROOT / 'CONFIDENCE_INTERVALS.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('\n'.join(lines))
